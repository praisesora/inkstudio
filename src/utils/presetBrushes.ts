let _assetsPrewarmed = false;

/**
 * Decodes all procedural builtin tip and paper PNG images into browser memory once
 * so the very first stroke on any preset hits already-decoded textures with zero latency.
 */
export function prewarmBuiltinBrushAssets(): void {
  if (_assetsPrewarmed || typeof document === 'undefined' || typeof Image === 'undefined') return;
  _assetsPrewarmed = true;
  for (let i = 0; i < BUILTIN_BRUSHES.length; i++) {
    const def = BUILTIN_BRUSHES[i];
    if (def.tipGenerator) {
      const url = def.tipGenerator();
      if (url) getPreloadedBuiltinTipImage(url);
    }
    if (def.subTipGenerators && def.subTipGenerators.length > 0) {
      for (let j = 0; j < def.subTipGenerators.length; j++) {
        const url = def.subTipGenerators[j]();
        if (url) getPreloadedBuiltinTipImage(url);
      }
    }
    if (def.dualTipGenerator) {
      const url = def.dualTipGenerator();
      if (url) getPreloadedBuiltinTipImage(url);
    }
    if (def.paperTextureGenerator) {
      const url = def.paperTextureGenerator();
      if (url) getPreloadedBuiltinTipImage(url);
    }
  }
}

// Schedule non-blocking prewarm in browser environments after initial paint
if (typeof window !== 'undefined' && typeof document !== 'undefined') {
  const scheduleWarm =
    typeof (window as unknown as { requestIdleCallback?: (cb: () => void) => number }).requestIdleCallback ===
    'function'
      ? (window as unknown as { requestIdleCallback: (cb: () => void) => number }).requestIdleCallback
      : (cb: () => void) => window.setTimeout(cb, 60);
  scheduleWarm(() => prewarmBuiltinBrushAssets());
}

/**
 * Returns the full brush settings for a builtin preset.
 */
export function getBuiltinBrushConfig(presetId: BrushPresetId): Partial<BrushSettings> | null {
  const def = BUILTIN_BRUSHES.find((b) => b.id === presetId);
  if (!def) return null;

  let tipDataUrl: string | undefined = undefined;
  let tipImage: HTMLImageElement | undefined = undefined;
  if (def.tipGenerator) {
    tipDataUrl = def.tipGenerator();
    if (tipDataUrl) {
      tipImage = getPreloadedBuiltinTipImage(tipDataUrl);
    }
  }

  let subTips: CspSubTip[] | undefined = undefined;
  let subTipImages: HTMLImageElement[] | undefined = undefined;
  if (def.subTipGenerators && def.subTipGenerators.length > 0) {
    const stW = def.subTipDimensions?.width ?? 256;
    const stH = def.subTipDimensions?.height ?? 256;
    const builtSubTips: CspSubTip[] = [];
    const builtImages: HTMLImageElement[] = [];
    for (let i = 0; i < def.subTipGenerators.length; i++) {
      const url = def.subTipGenerators[i]();
      if (!url) continue;
      builtSubTips.push({ dataUrl: url, width: stW, height: stH });
      const img = getPreloadedBuiltinTipImage(url);
      if (img) builtImages.push(img);
    }
    if (builtSubTips.length > 0) {
      subTips = builtSubTips;
      if (builtImages.length > 0) {
        subTipImages = builtImages;
      }
      if (!tipDataUrl) {
        tipDataUrl = builtSubTips[0].dataUrl;
        tipImage = builtImages[0];
      }
    }
  }

  let dualTipDataUrl: string | undefined = undefined;
  let dualTipImage: HTMLImageElement | undefined = undefined;
  if (def.dualTipGenerator) {
    dualTipDataUrl = def.dualTipGenerator();
    if (dualTipDataUrl) {
      dualTipImage = getPreloadedBuiltinTipImage(dualTipDataUrl);
    }
  }

  let paperTexture: string | undefined = undefined;
  let paperTextureImage: HTMLImageElement | undefined = undefined;
  if (def.paperTextureGenerator) {
    paperTexture = def.paperTextureGenerator();
    if (paperTexture) {
      paperTextureImage = getPreloadedBuiltinTipImage(paperTexture);
    }
  }

  const resolvedDualBrushConfig = def.settings.dualBrushConfig
    ? {
        ...def.settings.dualBrushConfig,
        tipDataUrl: dualTipDataUrl ?? def.settings.dualBrushConfig.tipDataUrl,
        tipImage: dualTipImage ?? def.settings.dualBrushConfig.tipImage,
      }
    : undefined;

  return {
    preset: def.id,
    brushName: def.name,
    customTipDataUrl: tipDataUrl,
    customTipImage: tipImage,
    subTips,
    subTipImages,
    dualTipDataUrl,
    dualTipImage,
    paperTexture,
    paperTextureImage,
    ...def.settings,
    ...(resolvedDualBrushConfig ? { dualBrushConfig: resolvedDualBrushConfig } : {}),
  };
}
